from app.features.export.pdf import header_links
from app.features.latex.convert import escape
from app.features.resume.models import ResumeDoc
from app.features.resume.render_text import date_range

preamble = r"""%-------------------------
% Resume in LaTeX, generated by Tailor
% Template: Jake's Resume (github.com/jakegut/resume), MIT License,
% Copyright (c) 2018 Jake Gutierrez
%-------------------------

\documentclass[letterpaper,11pt]{article}

\usepackage{latexsym}
\usepackage[empty]{fullpage}
\usepackage{titlesec}
\usepackage{marvosym}
\usepackage[usenames,dvipsnames]{color}
\usepackage{verbatim}
\usepackage{enumitem}
\usepackage[hidelinks]{hyperref}
\usepackage{fancyhdr}
\usepackage[english]{babel}
\usepackage{tabularx}
\input{glyphtounicode}

\pagestyle{fancy}
\fancyhf{}
\fancyfoot{}
\renewcommand{\headrulewidth}{0pt}
\renewcommand{\footrulewidth}{0pt}

\addtolength{\oddsidemargin}{-0.5in}
\addtolength{\evensidemargin}{-0.5in}
\addtolength{\textwidth}{1in}
\addtolength{\topmargin}{-.5in}
\addtolength{\textheight}{1.0in}

\urlstyle{same}
\raggedbottom
\raggedright
\setlength{\tabcolsep}{0in}

\titleformat{\section}{
  \vspace{-4pt}\scshape\raggedright\large
}{}{0em}{}[\color{black}\titlerule \vspace{-5pt}]

% Machine-readable PDF so ATS parsers extract real text
\pdfgentounicode=1

\newcommand{\resumeItem}[1]{
  \item\small{
    {#1 \vspace{-2pt}}
  }
}

\newcommand{\resumeSubheading}[4]{
  \vspace{-2pt}\item
    \begin{tabular*}{0.97\textwidth}[t]{l@{\extracolsep{\fill}}r}
      \textbf{#1} & #2 \\
      \textit{\small#3} & \textit{\small #4} \\
    \end{tabular*}\vspace{-7pt}
}

\newcommand{\resumeProjectHeading}[2]{
    \item
    \begin{tabular*}{0.97\textwidth}{l@{\extracolsep{\fill}}r}
      \small#1 & #2 \\
    \end{tabular*}\vspace{-7pt}
}

\renewcommand\labelitemii{$\vcenter{\hbox{\tiny$\bullet$}}$}

\newcommand{\resumeSubHeadingListStart}{\begin{itemize}[leftmargin=0.15in, label={}]}
\newcommand{\resumeSubHeadingListEnd}{\end{itemize}}
\newcommand{\resumeItemListStart}{\begin{itemize}}
\newcommand{\resumeItemListEnd}{\end{itemize}\vspace{-5pt}}
"""


def _link(url: str) -> str:
    href = url if "://" in url else f"https://{url}"
    shown = url.split("://")[-1].removeprefix("www.").rstrip("/")
    return rf"\href{{{href}}}{{\underline{{{escape(shown)}}}}}"


def _items(bullets: list[str]) -> list[str]:
    if not bullets:
        return []
    return [
        r"      \resumeItemListStart",
        *[rf"        \resumeItem{{{escape(b)}}}" for b in bullets],
        r"      \resumeItemListEnd",
    ]


def resume_latex(doc: ResumeDoc) -> str:
    c = doc.contact
    contact = [escape(p) for p in (c.phone,) if p]
    if c.email:
        contact.append(rf"\href{{mailto:{c.email}}}{{\underline{{{escape(c.email)}}}}}")
    if c.location:
        contact.append(escape(c.location))
    contact += [_link(url) for url in header_links(doc)]

    body = [r"\begin{document}", "", r"\begin{center}"]
    body.append(rf"    \textbf{{\Huge \scshape {escape(c.name)}}} \\ \vspace{{1pt}}")
    if c.headline:
        body.append(rf"    \small {escape(c.headline)} \\ \vspace{{1pt}}")
    if contact:
        body.append("    \\small " + " $|$ ".join(contact))
    body += [r"\end{center}", ""]

    if doc.summary:
        body += [r"\section{Summary}", rf"\small{{{escape(doc.summary)}}}", ""]

    if doc.experience:
        body += [r"\section{Experience}", r"  \resumeSubHeadingListStart"]
        for job in doc.experience:
            body.append(
                "    \\resumeSubheading"
                f"{{{escape(job.role)}}}{{{escape(date_range(job.start, job.end))}}}"
                f"{{{escape(job.company)}}}{{{escape(job.location or '')}}}"
            )
            body += _items(job.bullets)
        body += [r"  \resumeSubHeadingListEnd", ""]

    if doc.projects:
        body += [r"\section{Projects}", r"    \resumeSubHeadingListStart"]
        for project in doc.projects:
            link = _link(project.link) if project.link else ""
            body.append(
                rf"      \resumeProjectHeading{{\textbf{{{escape(project.name)}}}}}{{{link}}}"
            )
            body += _items(project.bullets)
        body += [r"    \resumeSubHeadingListEnd", ""]

    if doc.skills:
        body += [
            r"\section{Technical Skills}",
            r" \begin{itemize}[leftmargin=0.15in, label={}]",
            r"    \small{\item{",
        ]
        lines = [
            rf"     \textbf{{{escape(g.name)}}}{{: {escape(', '.join(g.items))}}}"
            for g in doc.skills
            if g.items
        ]
        body.append(" \\\\\n".join(lines))
        body += [r"    }}", r" \end{itemize}", ""]

    if doc.education:
        body += [r"\section{Education}", r"  \resumeSubHeadingListStart"]
        for ed in doc.education:
            body.append(
                "    \\resumeSubheading"
                f"{{{escape(ed.school)}}}{{{escape(date_range(ed.start, ed.end))}}}"
                f"{{{escape(ed.degree)}}}{{{escape(ed.location or '')}}}"
            )
            body += _items(ed.details)
        body += [r"  \resumeSubHeadingListEnd", ""]

    for extra in doc.extras:
        if extra.items:
            body += [rf"\section{{{escape(extra.title)}}}", r"  \resumeSubHeadingListStart"]
            body += [r"    \item\small{", *[rf"      {escape(i)} \\" for i in extra.items], "    }"]
            body += [r"  \resumeSubHeadingListEnd", ""]

    body.append(r"\end{document}")
    return preamble + "\n" + "\n".join(body) + "\n"
